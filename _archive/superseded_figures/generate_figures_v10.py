#  SUPPLEMENTARY S3 -- Robustness analysis
# ══════════════════════════════════════════════════════════════════════════════

def sup_s3():
    print("\n=== Supplementary S3: Robustness Analysis ===")
    fig, axes = plt.subplots(1, 3, figsize=(14, 5))

    # Panel A: Bootstrap CIs for frame proportions
    ax_a = axes[0]
    panel_label(ax_a, "A")

    n_boot = 500
    rng = np.random.RandomState(42)
    props_boot = {ft: [] for ft in TOP8_FRAMES}

    for _ in range(n_boot):
        sample = df_frame_cmb.sample(n=len(df_frame_cmb), replace=True)
        vc = sample["frame_type"].value_counts(normalize=True)
        for ft in TOP8_FRAMES:
            props_boot[ft].append(vc.get(ft, 0))

    means = [np.mean(props_boot[ft]) for ft in TOP8_FRAMES]
    ci_lo = [np.percentile(props_boot[ft], 2.5) for ft in TOP8_FRAMES]
    ci_hi = [np.percentile(props_boot[ft], 97.5) for ft in TOP8_FRAMES]
    yerr = np.array([[m - lo, hi - m] for m, lo, hi in zip(means, ci_lo, ci_hi)]).T

    ax_a.barh(range(len(TOP8_FRAMES)), means,
              xerr=yerr,
              color=[FRAME_CMAP[f] for f in TOP8_FRAMES],
              edgecolor="none", height=0.6, capsize=3)
    ax_a.set_yticks(range(len(TOP8_FRAMES)))
    ax_a.set_yticklabels(TOP8_FRAMES, fontsize=9)
    ax_a.invert_yaxis()
    ax_a.set_xlabel("Proportion (95% bootstrap CI)", fontsize=10)
    ax_a.set_title("Bootstrap frame proportions", fontsize=11, fontweight="bold")
    despine(ax_a)

    # Panel B: Sensitivity to year range
    ax_b = axes[1]
    panel_label(ax_b, "B")

    for ft in ["relay", "hub", "gate"]:
        taus = []
        starts = range(1980, 2010, 5)
        for start in starts:
            sub = df_frame_cmb[df_frame_cmb["year"] >= start]
            ct = sub.groupby(["year", "frame_type"]).size().unstack(fill_value=0)
            totals = ct.sum(axis=1)
            if ft in ct.columns:
                props = ct[ft] / totals
                tau, _, _, _ = mann_kendall(props.index.values, props.values)
                taus.append(tau)
            else:
                taus.append(np.nan)
        ax_b.plot(list(starts), taus, marker="o", label=ft,
                  color=FRAME_CMAP[ft], linewidth=1.5)
    ax_b.set_xlabel("Start year", fontsize=10)
    ax_b.set_ylabel("Mann-Kendall tau", fontsize=10)
    ax_b.set_title("Trend sensitivity to start year", fontsize=11, fontweight="bold")
    ax_b.legend(fontsize=9)
    ax_b.axhline(0, color="#999999", linewidth=0.6, linestyle="--")
    despine(ax_b)

    # Panel C: Frame detection precision (regex overlap)
    ax_c = axes[2]
    panel_label(ax_c, "C")

    # How many sentences match multiple frames?
    df_multi = df_all[df_all["frame_type"].fillna("") != ""].copy()
    # Count unique frame_type per sentence is always 1 in our data
    # Instead show n matches across different datasets
    labels_c = ["Abstract\nonly", "Full-text\nonly", "Combined"]
    vals_c = [len(df_frame_abs), len(df_frame_ft), len(df_frame_cmb)]
    ax_c.bar(labels_c, vals_c, color=[WONG["blue"], WONG["red"], WONG["green"]],
             edgecolor="none", width=0.5)
    for i, v in enumerate(vals_c):
        ax_c.text(i, v + 20, str(v), ha="center", fontsize=9)
    ax_c.set_ylabel("Number of framing sentences", fontsize=10)
    ax_c.set_title("Framing sentence counts by source", fontsize=11, fontweight="bold")
    despine(ax_c)

    fig.suptitle("Supplementary Figure S3: Robustness Analysis",
                 fontsize=14, fontweight="bold", y=1.02)
    fig.tight_layout()
    save_fig(fig, FIG_DIR / "sup_S3_robustness")
    plt.close(fig)
    print("  Done.")


