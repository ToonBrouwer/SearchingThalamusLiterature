def _nice_label(s: str, max_words: int = 4) -> str:
    """Capitalise + truncate a BERTopic label."""
    if not s or s == "unassigned":
        return s
    parts = s.split()
    parts[0] = parts[0].capitalize()
    if len(parts) > max_words:
        parts = parts[:max_words]
    return " ".join(parts)


def _short_label(s: str, max_words: int = 2) -> str:
    """Very short label for tight spaces."""
    if not s or s == "unassigned":
        return s
    parts = s.split()
    parts[0] = parts[0].capitalize()
    return " ".join(parts[:max_words])


def _frame_proportions(df, year_col="year", frame_col="frame_type",
                       year_min=None, year_max=None, smooth=3,
                       top_frames=None, group_other=True):
    """Build year x frame proportion matrix (smoothed)."""
    sub = df.copy()
    if year_min is not None:
        sub = sub[sub[year_col] >= year_min]
    if year_max is not None:
        sub = sub[sub[year_col] <= year_max]
    ct = sub.groupby([year_col, frame_col]).size().unstack(fill_value=0)
    year_totals = ct.sum(axis=1)
    props = ct.div(year_totals, axis=0).fillna(0)
    years = props.index.values
    if top_frames is None:
        top_frames = TOP8_FRAMES
    data = OrderedDict()
    colors = {}
    for ft in top_frames:
        if ft in props.columns:
            vals = rolling_mean(props[ft].values, smooth)
            data[ft] = vals
            colors[ft] = FRAME_CMAP.get(ft, WONG["grey"])
    if group_other:
        other_cols = [c for c in props.columns if c not in top_frames]
        if other_cols:
            other_sum = props[other_cols].sum(axis=1).values
            data["other metaphors"] = rolling_mean(other_sum, smooth)
            colors["other metaphors"] = WONG["ltgrey"]
    return years, data, colors


def _add_colorbar(fig, im, ax, label, pad=0.02, width=0.015):
    """Add a colorbar to the right of ax."""
    bbox = ax.get_position()
    cax = fig.add_axes([bbox.x1 + pad, bbox.y0, width, bbox.height])
    cb = fig.colorbar(im, cax=cax)
    cb.set_label(label, fontsize=8)
    cb.ax.tick_params(labelsize=7)
    return cb


def _heatmap_with_cbar(fig, ax, matrix, row_labels, col_labels,
                        cmap="YlOrRd", fmt=".1f", fontsize=6,
                        cbar_label="", vmin=None, vmax=None):
    """Heatmap with automatic colorbar."""
    matrix = np.asarray(matrix, dtype=float)
    im = ax.imshow(matrix, aspect="auto", cmap=cmap, vmin=vmin, vmax=vmax)
    ax.set_xticks(np.arange(len(col_labels)))
    ax.set_yticks(np.arange(len(row_labels)))
    ax.set_xticklabels(col_labels, rotation=45, ha="right", fontsize=fontsize)
    ax.set_yticklabels(row_labels, fontsize=fontsize)
    # Annotate cells
    thresh = matrix.max() / 2.0 if np.isfinite(matrix).any() else 0
    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            val = matrix[i, j]
            if not np.isfinite(val):
                continue
            colour = "white" if val > thresh else "black"
            ax.text(j, i, format(val, fmt), ha="center", va="center",
                    color=colour, fontsize=fontsize)
    ax.set_xticks(np.arange(len(col_labels) + 1) - 0.5, minor=True)
    ax.set_yticks(np.arange(len(row_labels) + 1) - 0.5, minor=True)
    ax.grid(which="minor", color="white", linewidth=1)
    ax.tick_params(which="minor", bottom=False, left=False)
    # Colorbar
    _add_colorbar(fig, im, ax, cbar_label)
    return im


