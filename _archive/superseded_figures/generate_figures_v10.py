    # Subsample for UMAP (max 15000)
    n = len(df_all)
    max_pts = 15000
    if n > max_pts:
        idx = np.random.RandomState(42).choice(n, max_pts, replace=False)
    else:
        idx = np.arange(n)

    print(f"  Running UMAP on {len(idx)} points ...")
    reducer = umap.UMAP(n_components=2, random_state=42, n_neighbors=15,
                         min_dist=0.1, metric="cosine")
    coords = reducer.fit_transform(embs[idx])

    topics_sub = df_all.iloc[idx]["topic_clean_v2"].values
    mega_sub = df_all.iloc[idx]["mega_theme"].values

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
    panel_label(ax1, "A")
    panel_label(ax2, "B")

    # Color by mega-theme
    for mt in MEGA_THEMES_ORDERED:
        mask = mega_sub == mt
        if mask.sum() == 0:
            continue
        ax1.scatter(coords[mask, 0], coords[mask, 1], s=1, alpha=0.3,
                    color=MEGA_CMAP.get(mt, WONG["grey"]), label=mt, rasterized=True)
    ax1.set_title("UMAP colored by mega-theme", fontsize=11, fontweight="bold")
    ax1.legend(fontsize=6, markerscale=5, framealpha=0.8)
    ax1.set_xlabel("UMAP-1")
    ax1.set_ylabel("UMAP-2")
    despine(ax1, top=False, right=False)
    ax1.set_xticks([])
    ax1.set_yticks([])

    # Color by top 10 topics
    top10 = df_all["topic_clean_v2"].value_counts().head(10).index.tolist()
    colors_top = list(WONG.values())
    for i, t in enumerate(top10):
        mask = topics_sub == t
        if mask.sum() == 0:
            continue
        ax2.scatter(coords[mask, 0], coords[mask, 1], s=1, alpha=0.3,
                    color=colors_top[i % len(colors_top)],
                    label=_nice_label(t, 3), rasterized=True)
    # Plot unassigned faintly
    mask_un = topics_sub == "unassigned"
    ax2.scatter(coords[mask_un, 0], coords[mask_un, 1], s=0.5, alpha=0.05,
                color="#cccccc", rasterized=True)
    ax2.set_title("UMAP colored by top 10 topics", fontsize=11, fontweight="bold")
    ax2.legend(fontsize=6, markerscale=5, framealpha=0.8)
    ax2.set_xlabel("UMAP-1")
    ax2.set_ylabel("UMAP-2")
    despine(ax2, top=False, right=False)
    ax2.set_xticks([])
    ax2.set_yticks([])

    fig.suptitle("Supplementary Figure S1: UMAP Embedding Space",
                 fontsize=14, fontweight="bold", y=1.02)
    fig.tight_layout()
    save_fig(fig, FIG_DIR / "sup_S1_umap_topics")
    plt.close(fig)
    print("  Done.")


